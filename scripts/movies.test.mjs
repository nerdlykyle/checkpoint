import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { changeMovie, makeMovie, movieId, moviesOnShelf, rateMovie, validateMovie } from '../src/lib/movies.ts'

const draft = {title:'The Last Signal',year:'2026',posterUrl:'',description:'A fictional film.'}
test('viewing uses an accessible reversible icon toggle instead of a dropdown', () => {
  const details=readFileSync(new URL('../src/MovieDetails.tsx',import.meta.url),'utf8')
  assert.doesNotMatch(details, /<select|movie-seen-select/)
  assert.match(details, /aria-label="Seen this movie" aria-pressed={hasSeen}/)
  assert.match(details, /onAction\(hasSeen \? 'unseen' : 'seen'\)/)
  assert.match(details, /hasSeen \? <Eye /)
  assert.match(details, /: <EyeOff /)
})
test('legacy movies need no migration and personal seen status stays separate from group history', async () => {
  const old = {...makeMovie(await movieId(draft),draft,'owner'),libraries:{owner:true,friend:true},clubStatus:'watching'}
  assert.equal(moviesOnShelf([old],'owner','watchlist').length,1)
  assert.equal(moviesOnShelf([old],'owner','watched').length,0)
  const seen = changeMovie(old,'owner','seen',old.id)
  assert.equal(seen.clubStatus,'watching')
  assert.equal(seen.seenBy.owner,true)
  assert.equal(seen.seenBy.friend,undefined)
  assert.equal(moviesOnShelf([seen],'owner','watched').length,1)
  assert.equal(moviesOnShelf([seen],'owner','watchlist').length,0)
  assert.equal(moviesOnShelf([seen],'friend','watchlist').length,1)
  const finished=changeMovie(seen,'owner','finish',seen.id)
  assert.deepEqual(finished.seenBy,{owner:true})
  assert.equal(moviesOnShelf([finished],'friend','watched').length,0)
  const removed=changeMovie(seen,'owner','remove',seen.id)
  assert.equal(moviesOnShelf([removed],'owner','watched').length,0)
  assert.equal(changeMovie(removed,'owner','save',seen.id).seenBy.owner,true)
  assert.equal(changeMovie(seen,'owner','unseen',seen.id).seenBy.owner,false)
})
test('ratings preserve friends, permit clearing and do not change shelves', async () => {
  const old={...makeMovie(await movieId(draft),draft,'owner'),ratings:{friend:4}}
  const rated=rateMovie(old,'owner',5)
  assert.deepEqual(rated.ratings,{friend:4,owner:5})
  assert.deepEqual(rateMovie(rated,'owner',0).ratings,{friend:4,owner:0})
  assert.deepEqual(rated.libraries,old.libraries)
  assert.equal(rated.seenBy,undefined)
  for(const invalid of [-1,6,1.5,NaN,'5']) assert.throws(()=>rateMovie(old,'owner',invalid))
})
test('browsing a friend’s library filters their shelves while saving changes only your copy', async () => {
  const friendMovie=changeMovie(makeMovie(await movieId(draft),draft,'friend'),'friend','seen','')
  assert.equal(moviesOnShelf([friendMovie],'owner','all').length,0)
  assert.equal(moviesOnShelf([friendMovie],'friend','all').length,1)
  assert.equal(moviesOnShelf([friendMovie],'friend','watched').length,1)
  assert.equal(moviesOnShelf([friendMovie],'friend','watchlist').length,0)
  const saved=changeMovie(friendMovie,'owner','save','')
  assert.equal(moviesOnShelf([saved],'owner','watchlist').length,1)
  assert.equal(moviesOnShelf([saved],'friend','watched').length,1)
  assert.deepEqual(saved.seenBy,{friend:true})
  const removed=changeMovie(saved,'owner','remove','')
  assert.equal(moviesOnShelf([removed],'owner','all').length,0)
  assert.equal(moviesOnShelf([removed],'friend','watched').length,1)
  const ui=readFileSync(new URL('../src/MovieMode.tsx',import.meta.url),'utf8')
  assert.match(ui,/moviesOnShelf\(store.items, reader, library, favoriteIds\)/)
  assert.match(ui,/useMovieStore\(props.boardId, props.user, props.boardReady\)/)
  assert.match(ui,/<MovieDetails[^>]+user={user}/)
})
test('group watchlist is shared and sorted without altering personal libraries', async () => {
  const old=makeMovie(await movieId(draft),draft,'friend')
  const queued=changeMovie(old,'owner','queue','')
  assert.equal(moviesOnShelf([queued],'owner','group').length,1)
  assert.equal(moviesOnShelf([queued],'owner','all').length,0)
  assert.equal(moviesOnShelf([queued],'friend','watchlist').length,1)
  assert.equal(moviesOnShelf([changeMovie(queued,'owner','unqueue','')],'owner','group').length,0)
})
test('movie validation rejects unsafe art and invalid fields', () => {
  assert.throws(() => validateMovie({...draft,title:' '}))
  assert.throws(() => validateMovie({...draft,year:'abc'}))
  for (const posterUrl of ['javascript:alert(1)','data:image/png;base64,AAA','http://example.test/art.jpg','https://user:pass@example.test/image']) assert.throws(() => validateMovie({...draft,posterUrl}))
  assert.throws(() => validateMovie({...draft,description:'x'.repeat(5001)}))
  assert.equal(validateMovie({...draft,title:' A film '}).title,'A film')
})
test('movie ids deduplicate title/year without merging remakes', async () => {
  assert.equal(await movieId(draft),await movieId({...draft,title:' the LAST   signal '}))
  assert.notEqual(await movieId(draft),await movieId({...draft,year:'1984'}))
})
test('personal removal preserves other members, metadata, and group watch', async () => {
  const item = {...makeMovie(await movieId(draft),draft,'owner'),libraries:{owner:true,friend:true},clubStatus:'watching'}
  const removed=changeMovie(item,'owner','remove',item.id)
  assert.deepEqual(removed.libraries,{owner:false,friend:true})
  assert.equal(removed.clubStatus,'watching');assert.equal(item.libraries.owner,true)
  assert.deepEqual(changeMovie(removed,'owner','save',item.id),item)
})
test('queue and group-watch transitions cannot replace an active movie',async()=>{
  const item=makeMovie(await movieId(draft),draft,'owner')
  const queued=changeMovie(item,'owner','queue','')
  assert.equal(queued.clubStatus,'up-next');assert.ok(queued.queuedAt)
  assert.equal(changeMovie(queued,'owner','queue','').queuedAt,queued.queuedAt)
  assert.throws(()=>changeMovie(item,'owner','start','another-movie'))
  const playing=changeMovie(queued,'owner','start','')
  assert.throws(()=>changeMovie(playing,'owner','unqueue',item.id))
  assert.throws(()=>changeMovie(playing,'owner','finish','another-movie'))
  assert.equal(changeMovie(playing,'owner','finish',item.id).clubStatus,'watched')
  assert.equal(changeMovie(queued,'owner','unqueue','').clubStatus,'none')
})
